import { Place } from "@repo/shared-types";
import Database from "better-sqlite3";
import BetterSqlite3 from "better-sqlite3";

export function initDatabase(path: string): BetterSqlite3.Database {
  const db = new Database(path);
  db.exec(
    `CREATE TABLE IF NOT EXISTS places (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT NOT NULL,
      location TEXT NOT NULL,
      latitude REAL NOT NULL,
      longtitude REAL NOT NULL,
      biome TEXT NOT NULL,
      description TEXT NOT NULL,
      imageUrl TEXT NOT NULL
    );`,
  );
  return db;
}

export function getAllPlaces(db: BetterSqlite3.Database): Place[] {
  const query = db.prepare<[], Place>(
    "SELECT name, location, latitude, longtitude, biome, description, imageUrl FROM places",
  );
  return query.all();
}

export function seedDatabase(db: BetterSqlite3.Database) {
  if (getAllPlaces(db).length !== 0) return;

  const insertion = db.prepare(
    `INSERT INTO places (name, location, latitude, longtitude, biome, description, imageUrl)
    VALUES (@name, @location, @latitude, @longtitude, @biome, @description, @imageUrl)`,
  );
  insertion.run({
    name: "Stonehenge Grass",
    location: "Salisbury Plain, Wiltshire, England",
    latitude: 51.178889,
    longtitude: -1.826111,
    biome: "Temporal Broadleaf",
    description: "Bruh",
    imageUrl:
      "https://thumb.wikimedia.org/wikipedia/commons/thumb/3/3c/Stonehenge2007_07_30.jpg/330px-Stonehenge2007_07_30.jpg?utm_source=en.wikipedia.org&utm_campaign=parser&utm_content=thumbnail",
  });
  
}

export function getTotalPlaces(db: BetterSqlite3.Database): number {
  const query = db.prepare("SELECT MAX(id) AS max_id FROM places").get() as any;
  const maxid = query?.max_id ?? 0;

  return maxid;
}

export function getPlaceById(db: BetterSqlite3.Database, id: number): Place {
  const query = db.prepare(
    "SELECT name, location, latitude, longtitude, biome, description, imageUrl FROM places WHERE id = ?",
  );
  return query.get(id);
}

export function addPlace(db: BetterSqlite3.Database, place: Place) {
  const insertion = db.prepare(
    `INSERT INTO places (name, location, latitude, longtitude, biome, description, imageUrl)
    VALUES (@name, @location, @latitude, @longtitude, @biome, @description, @imageUrl)`,
  );
  insertion.run(place);
}

